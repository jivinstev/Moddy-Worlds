#!/usr/bin/env python3
"""core-pins.py — each world's core pin: written once, in its Port CI workflow, and copied into its core.lock.

    python3 tools/core-pins.py --set <world|all> <core tag> [--mmvu DIR]   # THE way to bump a world's core
    python3 tools/core-pins.py --regenerate <world|all> [--mmvu DIR]       # same pin, the branch .github/port-ci-branch names
    python3 tools/core-pins.py --write                                     # every core.lock, from the workflows
    python3 tools/core-pins.py --check                                     # exit 1 on any disagreement (CI)
    python3 tools/core-pins.py --self-test

THE ONE WRITER. Each world ships with its own Port CI workflow, .github/workflows/port-ci-<world>.yml, generated by
MMVU's tools/port-ci.py (never edited by hand). Its --dep-jar step downloads the public core release jar, checks its
sha256 and installs it into mavenLocal as com.moddingfromamod:moddingfromamod:<core version>: that step IS the pin.
MMVU's real-install reads it there too (a `curl` line with the release URL, the sha256 on the next line).

<world>/core.lock keeps its keys (core_repo, core_tag, core_asset, core_sha256) for what reads it -- the build
(shared/level.gradle, which sha256-checks the core it compiles against, from mavenLocal or <world>/.core/),
tools/fetch-core.sh, tools/play.sh, tools/check-level-jar.py -- but it is GENERATED from the workflow by --write, with a
header saying so. Each world, and each branch, keeps its own pin.

  --set W TAG   resolves the core release TAG (moddingfromamod-<version>-mc<minecraft>, on the repository the world's
                core.lock names): its one moddingfromamod-*.jar asset and that asset's sha256 (from the release's
                SHA256SUMS asset when it has one, else by downloading the jar and hashing it). It refuses a tag for
                another Minecraft than the world's, and a version outside the world's core_version_range. Then it
                regenerates the world's workflow with MMVU's tools/port-ci.py (the workflow's own options read back,
                `port-ci.py args`, with only the --dep-jar pin changed; its kit stays) and rewrites its core.lock.
                W `all` does every world. MMVU is --mmvu DIR, else $MMVU, else ../mc-mod-version-upgrade beside this
                repository. Commit the workflow and core.lock together.
  --regenerate W  regenerates the world's workflow (or every world's) with its pin unchanged: after editing
                .github/port-ci-branch, the ONE place that names the branch the workflows run on and release from (`main`
                today; `neoforge-1.21.8` if this repository gets a release-line branch), or to move to the newest kit.
                --set and --regenerate both pass that branch to port-ci.py as --branch. Unlike --set, --regenerate lets
                port-ci.py pick the newest Port CI kit.
  --write       rewrites every core.lock from its world's workflow.
  --check       for every world: its workflow pins the core exactly once, the pinned version is the one its tag names,
                core.lock is exactly what --write would write, and the pinned version satisfies the world's hand-kept
                core_version_range (gradle.properties, a Maven range like [1.0.9,) ), and the workflow runs on the
                branch .github/port-ci-branch names. Exit 1 otherwise, naming each.
"""
import argparse
import hashlib
import json
import os
import pathlib
import re
import shlex
import subprocess
import sys
import tempfile
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
WORKFLOWS = ".github/workflows"
GROUP, ARTIFACT = "com.moddingfromamod", "moddingfromamod"
GA = f"{GROUP}:{ARTIFACT}"
KEYS = ("core_repo", "core_tag", "core_asset", "core_sha256")
BRANCH_FILE = ".github/port-ci-branch"     # the one place naming the branch every world's Port CI runs on


def release_branch(root=ROOT):
    """The branch every world's Port CI workflow runs on and releases from (.github/port-ci-branch, one line)."""
    f = pathlib.Path(root) / BRANCH_FILE
    b = f.read_text(encoding="utf-8").strip() if f.is_file() else ""
    if not re.fullmatch(r"[\w.\-/]+", b):
        raise SystemExit(f"core-pins: {BRANCH_FILE} must hold one branch name (e.g. main), got {b!r}")
    return b


def workflow_branch(text):
    """The branch a Port CI workflow's push trigger names, or None."""
    m = re.search(r'(?m)^  push:\n    branches: \["([^"]+)"\]', text)
    return m.group(1) if m else None

# The --dep-jar step port-ci.py renders (tools/port-ci.py dep_jars): its name, the mavenLocal folder, the release URL
# and the sha256 on the next line.
STEP = re.compile(
    r'- name: (?P<art>[\w.-]+) (?P<ver>[\w.+-]+) from the (?P<tag>[^\s]+) release into mavenLocal \(pinned by sha256\)\n'
    r'\s*run: \|\n'
    r'\s*mkdir -p "\$HOME/\.m2/repository/(?P<path>[^"]+)"\n'
    r'\s*curl -fsSL -o "[^"]+" "https://github\.com/(?P<repo>[^/"]+/[^/"]+)/releases/download/(?P<tag2>[^/"]+)/(?P<asset>[^/"]+)"\n'
    r'\s*echo "(?P<sha>[0-9a-f]{64})  [^"]+" \| sha256sum -c -\n')


def read_props(path):
    out = {}
    for line in pathlib.Path(path).read_text(encoding="utf-8").splitlines():
        if "=" in line and not line.lstrip().startswith("#"):
            k, v = line.split("=", 1)
            out[k.strip()] = v.strip()
    return out


def worlds(root=ROOT):
    """Every world: a top-level folder holding core.lock (as tools/changed-worlds.py finds them)."""
    return sorted(p.parent.name for p in pathlib.Path(root).glob("*/core.lock"))


def workflow_of(world, root=ROOT):
    return pathlib.Path(root) / WORKFLOWS / f"port-ci-{world}.yml"


def pins_in(text):
    """[{repo, tag, asset, sha256, group, artifact, version}] for every --dep-jar step in a workflow text."""
    out = []
    for m in STEP.finditer(text):
        art, ver, path = m["art"], m["ver"], m["path"]
        suffix = f"/{art}/{ver}"
        if not path.endswith(suffix) or m["tag"] != m["tag2"]:
            continue
        out.append({"repo": m["repo"], "tag": m["tag"], "asset": m["asset"], "sha256": m["sha"],
                    "group": path[:-len(suffix)].replace("/", "."), "artifact": art, "version": ver})
    return out


def core_pin(text):
    """The one core pin (com.moddingfromamod:moddingfromamod) in a workflow text, or a ValueError saying why not."""
    pins = [p for p in pins_in(text) if (p["group"], p["artifact"]) == (GROUP, ARTIFACT)]
    if len(pins) != 1:
        raise ValueError(f"pins {GA} {len(pins)} time(s) (want exactly one --dep-jar step for it)")
    return pins[0]


def version_of_tag(tag, mc):
    """The core version a core release tag names (moddingfromamod-<version>-mc<mc>), or None: the same rule
    shared/level.gradle uses to find the jar in mavenLocal."""
    pre, suf = f"{ARTIFACT}-", f"-mc{mc}"
    return tag[len(pre):-len(suf)] if tag.startswith(pre) and tag.endswith(suf) and len(tag) > len(pre) + len(suf) else None


def header(world):
    return (f"# GENERATED by tools/core-pins.py --write from .github/workflows/port-ci-{world}.yml (Port CI's --dep-jar pin"
            f" of {GA}). Do not edit.\n"
            f"# Change the pin with: python3 tools/core-pins.py --set {world} <core tag>   (then commit the workflow and"
            f" this file)\n")


def lock_text(world, pin):
    return header(world) + "".join(f"{k}={pin[k[5:]]}\n" for k in KEYS)


# ── Maven version ranges (core_version_range, as neoforge.mods.toml reads it) ──────────────────────────────────────────
def _vkey(v):
    """A comparable key for a dotted version: numeric parts as numbers, a qualifier (-beta) below the release."""
    main, _, qual = v.partition("-")
    nums = []
    for part in re.split(r"[.+]", main):
        nums.append((0, int(part), "") if part.isdigit() else (1, 0, part))
    while nums and nums[-1] == (0, 0, ""):
        nums.pop()
    return (nums, 0 if qual else 1, qual)


def in_range(version, spec):
    """Does `version` satisfy a Maven range: [a,b), (a,], [a], several joined by commas, or a bare version (>= it)?"""
    spec = spec.replace(" ", "")
    if not spec:
        return False
    if spec[0] not in "[(":
        return _vkey(version) >= _vkey(spec)
    for lo_b, body, hi_b in re.findall(r"([\[(])([^\[\]()]*)([\])])", spec):
        if "," not in body:
            if lo_b == "[" and hi_b == "]" and _vkey(version) == _vkey(body):
                return True
            continue
        lo, hi = body.split(",", 1)
        ok = True
        if lo:
            ok &= _vkey(version) >= _vkey(lo) if lo_b == "[" else _vkey(version) > _vkey(lo)
        if hi:
            ok &= _vkey(version) <= _vkey(hi) if hi_b == "]" else _vkey(version) < _vkey(hi)
        if ok:
            return True
    return False


# ── --check / --write ────────────────────────────────────────────────────────────────────────────────────────────────
def world_problems(world, root=ROOT):
    """(the core.lock text --write would write, or None; [what is wrong])."""
    d = pathlib.Path(root) / world
    wf = workflow_of(world, root)
    if not wf.is_file():
        return None, [f"{world}: no {wf.relative_to(root).as_posix()} (generate it with MMVU's tools/port-ci.py --mod-dir "
                      f"{world} ... --dep-jar ..., or tools/core-pins.py --set {world} <core tag>)"]
    text = wf.read_text(encoding="utf-8")
    try:
        pin = core_pin(text)
    except ValueError as e:
        return None, [f"{world}: {wf.relative_to(root).as_posix()} {e}"]
    props = read_props(d / "gradle.properties")
    bad = []
    want_branch = release_branch(root)
    if workflow_branch(text) != want_branch:
        bad.append(f"{world}: {wf.name} runs on {workflow_branch(text)!r}, but {BRANCH_FILE} names {want_branch!r}: "
                   f"run tools/core-pins.py --regenerate {world}")
    mc = props.get("minecraft_version", "")
    if version_of_tag(pin["tag"], mc) != pin["version"]:
        bad.append(f"{world}: the workflow pins {GA}:{pin['version']} from release {pin['tag']}, which is not the core "
                   f"{pin['version']} for Minecraft {mc} (shared/level.gradle reads the version from the tag)")
    rng = props.get("core_version_range", "")
    if not in_range(pin["version"], rng):
        bad.append(f"{world}: the pinned core {pin['version']} is outside its core_version_range {rng or '(none)'} "
                   f"({world}/gradle.properties)")
    want = lock_text(world, pin)
    have = (d / "core.lock").read_text(encoding="utf-8") if (d / "core.lock").is_file() else ""
    if have.replace("\r\n", "\n") != want:
        bad.append(f"{world}: core.lock is not its workflow's pin: run tools/core-pins.py --write")
    return want, bad


def run_check(root=ROOT, out=sys.stdout, err=sys.stderr):
    ws = worlds(root)
    if not ws:
        print("core-pins: no */core.lock", file=err)
        return 2
    bad = []
    for w in ws:
        bad += world_problems(w, root)[1]
    for b in bad:
        print(f"core-pins: {b}", file=err)
    if not bad:
        print(f"core-pins: {', '.join(ws)}: core.lock matches each workflow's pin, within core_version_range", file=out)
    return 1 if bad else 0


def run_write(root=ROOT, only=None, out=sys.stdout, err=sys.stderr):
    rc = 0
    for w in (only or worlds(root)):
        want, bad = world_problems(w, root)
        if want is None:
            for b in bad:
                print(f"core-pins: {b}", file=err)
            rc = 1
            continue
        lock = pathlib.Path(root) / w / "core.lock"
        if (lock.read_text(encoding="utf-8") if lock.is_file() else None) != want:
            with open(lock, "w", encoding="utf-8", newline="\n") as f:     # LF on every system
                f.write(want)
            print(f"core-pins: wrote {w}/core.lock", file=out)
        for b in bad:
            if "core.lock is not" not in b and BRANCH_FILE not in b:
                print(f"core-pins: {b}", file=err)
                rc = 1
    return rc


# ── --set ────────────────────────────────────────────────────────────────────────────────────────────────────────────
def _get(url, accept=None):
    headers = {"User-Agent": "core-pins", **({"Accept": accept} if accept else {})}
    with urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=300) as r:
        return r.read()


def resolve(repo, tag, get=_get):
    """(asset, sha256) of the core release `tag` on `repo`: its one moddingfromamod-*.jar asset (no -sources/-api jar),
    and its sha256 from the release's SHA256SUMS asset when there is one, else by downloading and hashing it."""
    rel = json.loads(get(f"https://api.github.com/repos/{repo}/releases/tags/{tag}", "application/vnd.github+json"))
    names = [a["name"] for a in rel.get("assets") or []]
    jars = [n for n in names if re.fullmatch(rf"{ARTIFACT}-[\w.+-]+\.jar", n)
            and not re.search(r"-(sources|api|javadoc|dev)\.jar$", n)]
    if len(jars) != 1:
        raise SystemExit(f"core-pins: release {tag} of {repo} has {len(jars)} core jar(s) ({', '.join(jars) or 'none'}): "
                         "cannot tell which one to pin")
    asset = jars[0]
    if "SHA256SUMS" in names:
        sums = get(f"https://github.com/{repo}/releases/download/{tag}/SHA256SUMS").decode("utf-8", "replace")
        m = re.search(rf"(?m)^([0-9a-f]{{64}})\s+\*?(?:\./)?{re.escape(asset)}\s*$", sums)
        if not m:
            raise SystemExit(f"core-pins: release {tag}'s SHA256SUMS names no {asset}")
        return asset, m.group(1)
    data = get(f"https://github.com/{repo}/releases/download/{tag}/{asset}")
    return asset, hashlib.sha256(data).hexdigest()


def mmvu_dir(given=None):
    d = pathlib.Path(given or os.environ.get("MMVU") or (ROOT.parent / "mc-mod-version-upgrade"))
    if not (d / "tools" / "port-ci.py").is_file():
        raise SystemExit(f"core-pins: no MMVU at {d} (tools/port-ci.py): clone https://github.com/jivinstev/"
                         "mc-mod-version-upgrade there, or pass --mmvu DIR")
    return d


def regenerate_args(recovered, spec, branch, keep_kit=True):
    """The port-ci.py arguments for the regenerated workflow: the ones read back from it (`port-ci.py args`), with
    the core's --dep-jar replaced by `spec` and --branch the branch it runs on; nothing else moves."""
    args, i = [], 0
    while i < len(recovered):
        a = recovered[i]
        if a in ("--dep-jar",) and i + 1 < len(recovered):
            if recovered[i + 1].endswith(f"={GA}:" + recovered[i + 1].rsplit(":", 1)[-1]):
                i += 2
                continue
            args += [a, recovered[i + 1]]
            i += 2
            continue
        if a == "--branch" or (not keep_kit and a in ("--kit-version", "--kit-sha")):
            i += 2
            continue
        args.append(a)
        i += 1
    return args + ["--dep-jar", spec, "--branch", branch]


def regenerate(world, spec, tool, root=ROOT, keep_kit=True, run=subprocess.run):
    """Regenerate port-ci-<world>.yml with MMVU's port-ci.py: its own options read back (`port-ci.py args`), the core's
    --dep-jar set to `spec`, --branch the one .github/port-ci-branch names. -> the pin the new workflow holds."""
    wf = workflow_of(world, root)
    if not wf.is_file():
        raise SystemExit(f"core-pins: no {wf.relative_to(root).as_posix()}: generate it first with MMVU's "
                         f"tools/port-ci.py --mod-dir {world} (README: Adding a world)")
    r = run([sys.executable, str(tool), "args", "--repo", str(root), "--file", str(wf)], capture_output=True,
            text=True, encoding="utf-8")
    if r.returncode:
        raise SystemExit(f"core-pins: port-ci.py args failed on {wf.name}: {(r.stdout + r.stderr).strip()}")
    recovered = shlex.split(r.stdout.strip())
    recovered = recovered[recovered.index("--repo") + 2:]          # drop "python3 tools/port-ci.py --repo DIR"
    args = regenerate_args(recovered, spec, release_branch(root), keep_kit)
    r = run([sys.executable, str(tool), "--repo", str(root), *args, "--no-commit"], capture_output=True, text=True,
            encoding="utf-8")
    if r.returncode:
        raise SystemExit(f"core-pins: port-ci.py could not regenerate {wf.name}: {(r.stdout + r.stderr).strip()}")
    return core_pin(wf.read_text(encoding="utf-8"))


def targets_of(target, root):
    ws = worlds(root) if target == "all" else [target]
    for w in ws:
        if w not in worlds(root):
            raise SystemExit(f"core-pins: no world {w!r} (a top-level folder with core.lock); the worlds: "
                             f"{', '.join(worlds(root))}")
    return ws


def run_regenerate(target, mmvu=None, root=ROOT):
    tool = mmvu_dir(mmvu) / "tools" / "port-ci.py"
    ws = targets_of(target, root)
    for w in ws:
        try:
            pin = core_pin(workflow_of(w, root).read_text(encoding="utf-8"))
        except (OSError, ValueError) as e:
            raise SystemExit(f"core-pins: {w}: cannot read its workflow's core pin ({e})")
        spec = f"{pin['repo']}@{pin['tag']}/{pin['asset']}={GA}:{pin['version']}"
        regenerate(w, spec, tool, root, keep_kit=False)
        print(f"core-pins: {w}: regenerated {workflow_of(w, root).relative_to(root).as_posix()} on branch "
              f"{release_branch(root)}, pin unchanged ({pin['tag']})")
    return run_write(root, ws)


def run_set(target, tag, mmvu=None, root=ROOT, get=_get):
    ws = targets_of(target, root)
    tool = mmvu_dir(mmvu) / "tools" / "port-ci.py"
    resolved = {}
    for w in ws:
        d = pathlib.Path(root) / w
        props, lock = read_props(d / "gradle.properties"), read_props(d / "core.lock")
        repo, mc = lock.get("core_repo"), props.get("minecraft_version", "")
        if not repo:
            raise SystemExit(f"core-pins: {w}/core.lock names no core_repo")
        ver = version_of_tag(tag, mc)
        if not ver:
            raise SystemExit(f"core-pins: {tag} is not a core release for {w}'s Minecraft {mc} "
                             f"({ARTIFACT}-<version>-mc{mc})")
        rng = props.get("core_version_range", "")
        if not in_range(ver, rng):
            raise SystemExit(f"core-pins: core {ver} is outside {w}'s core_version_range {rng}: change the range in "
                             f"{w}/gradle.properties first (it is kept by hand), then --set again")
        if (repo, tag) not in resolved:
            resolved[(repo, tag)] = resolve(repo, tag, get)
        asset, sha = resolved[(repo, tag)]
        pin = regenerate(w, f"{repo}@{tag}/{asset}={GA}:{ver}", tool, root)
        if (pin["tag"], pin["asset"], pin["sha256"], pin["version"]) != (tag, asset, sha, ver):
            raise SystemExit(f"core-pins: the regenerated port-ci-{w}.yml pins {pin}, not {tag}/{asset} {sha}")
        print(f"core-pins: {w}: port-ci-{w}.yml pins {GA}:{ver} ({tag}/{asset}, sha256 {sha})")
    return run_write(root, ws)


# ── self-test ────────────────────────────────────────────────────────────────────────────────────────────────────────
def _step(repo, tag, asset, ver, sha, art=ARTIFACT, group=GROUP):
    dest = "$HOME/.m2/repository/" + group.replace(".", "/") + f"/{art}/{ver}"
    return (f"      - name: {art} {ver} from the {tag} release into mavenLocal (pinned by sha256)\n"
            f"        run: |\n"
            f'          mkdir -p "{dest}"\n'
            f'          curl -fsSL -o "{dest}/{art}-{ver}.jar" "https://github.com/{repo}/releases/download/{tag}/{asset}"\n'
            f'          echo "{sha}  {dest}/{art}-{ver}.jar" | sha256sum -c -\n'
            f"          echo '<project/>' > \"{dest}/{art}-{ver}.pom\"\n")


def self_test():
    sha = "a" * 64
    tag, asset = "moddingfromamod-1.0.10-mc1.21.8", "moddingfromamod-1.0.10+mc1.21.8.jar"
    wf_text = ("on:\n  push:\n    branches: [\"main\"]\njobs:\n  gates:\n    steps:\n"
               + _step("o/core", tag, asset, "1.0.10", sha) + _step("o/lib", "lib-2-mc1.21.8", "lib-2.jar", "2", "b" * 64,
                                                                   art="lib", group="org.example"))
    pin = core_pin(wf_text)
    assert pin == {"repo": "o/core", "tag": tag, "asset": asset, "sha256": sha, "group": GROUP, "artifact": ARTIFACT,
                   "version": "1.0.10"}, pin
    assert len(pins_in(wf_text)) == 2
    try:
        core_pin(wf_text + _step("o/core", tag, asset, "1.0.10", sha))
        raise AssertionError("two core pins must be refused")
    except ValueError as e:
        assert "2 time(s)" in str(e)
    assert version_of_tag(tag, "1.21.8") == "1.0.10" and version_of_tag(tag, "1.21.10") is None
    # Maven ranges
    for v, r, want in [("1.0.10", "[1.0.9,)", True), ("1.0.8", "[1.0.9,)", False), ("1.0.9", "[1.0.9,)", True),
                       ("1.0.10", "[1.0.9,1.0.10)", False), ("1.0.10", "[1.0.9,1.0.10]", True),
                       ("1.0.10", "(1.0.10,)", False), ("1.0.10", "[1.0.10]", True), ("1.1", "[1.0,1.0.5),[1.1,)", True),
                       ("1.0.10", "1.0.9", True), ("1.0.10", "", False), ("1.0.10", "[1.0.2,1.0.9]", False)]:
        assert in_range(v, r) is want, (v, r, want)
    # --write / --check on a fixture repository
    with tempfile.TemporaryDirectory() as d:
        root = pathlib.Path(d)
        (root / WORKFLOWS).mkdir(parents=True)
        (root / BRANCH_FILE).write_text("main\n", encoding="utf-8")
        for w in ("arena", "isle"):
            (root / w).mkdir()
            (root / w / "gradle.properties").write_text("minecraft_version=1.21.8\ncore_version_range=[1.0.9,)\n",
                                                        encoding="utf-8")
            (root / w / "core.lock").write_text("core_repo=old\n", encoding="utf-8")
            workflow_of(w, root).write_text(wf_text, encoding="utf-8")
        quiet = open(os.devnull, "w", encoding="utf-8")
        assert run_check(root, quiet, quiet) == 1, "a hand-written core.lock disagrees"
        assert run_write(root, out=quiet, err=quiet) == 0
        assert run_check(root, quiet, quiet) == 0
        text = (root / "arena" / "core.lock").read_text(encoding="utf-8")
        assert text.startswith("# GENERATED by tools/core-pins.py") and "--set arena <core tag>" in text
        assert read_props(root / "arena" / "core.lock") == {"core_repo": "o/core", "core_tag": tag, "core_asset": asset,
                                                            "core_sha256": sha}
        assert run_write(root, out=quiet, err=quiet) == 0 and (root / "arena" / "core.lock").read_text(
            encoding="utf-8") == text, "idempotent"
        # a hand edit of core.lock is caught
        (root / "isle" / "core.lock").write_text(text.replace(sha, "c" * 64), encoding="utf-8")
        assert run_check(root, quiet, quiet) == 1
        run_write(root, out=quiet, err=quiet)
        # the pinned version outside a world's core_version_range is caught, per world
        (root / "isle" / "gradle.properties").write_text("minecraft_version=1.21.8\ncore_version_range=[1.1,)\n",
                                                         encoding="utf-8")
        assert any("outside its core_version_range" in b for b in world_problems("isle", root)[1])
        assert world_problems("arena", root)[1] == []
        assert run_check(root, quiet, quiet) == 1
        (root / "isle" / "gradle.properties").write_text("minecraft_version=1.21.8\ncore_version_range=[1.0.9,)\n",
                                                         encoding="utf-8")
        # the branch is named once: a workflow on another branch than .github/port-ci-branch is caught
        (root / BRANCH_FILE).write_text("neoforge-1.21.8\n", encoding="utf-8")
        assert any("--regenerate arena" in b for b in world_problems("arena", root)[1])
        assert run_write(root, out=quiet, err=quiet) == 0, "--write still writes core.lock; the branch is --regenerate's"
        (root / BRANCH_FILE).write_text("main\n", encoding="utf-8")
        assert world_problems("arena", root)[1] == []
        # a world with no workflow, or one whose pinned version is not its tag's
        workflow_of("isle", root).unlink()
        assert any("no .github/workflows/port-ci-isle.yml" in b for b in world_problems("isle", root)[1])
        workflow_of("isle", root).write_text(wf_text.replace("mavenLocal", "mavenLocal").replace(
            "/moddingfromamod/1.0.10", "/moddingfromamod/1.0.11").replace("moddingfromamod 1.0.10 from",
                                                                           "moddingfromamod 1.0.11 from"),
            encoding="utf-8")
        assert any("not the core 1.0.11" in b for b in world_problems("isle", root)[1]), world_problems("isle", root)
        # --set's resolution: SHA256SUMS when the release has it, else the jar's own hash
        rel = {"assets": [{"name": "gates-full.md"}, {"name": asset}, {"name": "moddingfromamod-1.0.10-sources.jar"}]}
        fake = {f"https://api.github.com/repos/o/core/releases/tags/{tag}": json.dumps(rel).encode(),
                f"https://github.com/o/core/releases/download/{tag}/{asset}": b"jar bytes"}
        assert resolve("o/core", tag, lambda u, a=None: fake[u]) == (asset, hashlib.sha256(b"jar bytes").hexdigest())
        rel["assets"].append({"name": "SHA256SUMS"})
        fake[f"https://api.github.com/repos/o/core/releases/tags/{tag}"] = json.dumps(rel).encode()
        fake[f"https://github.com/o/core/releases/download/{tag}/SHA256SUMS"] = f"{'d' * 64}  {asset}\n".encode()
        assert resolve("o/core", tag, lambda u, a=None: fake[u]) == (asset, "d" * 64)
        # --set's regeneration keeps every option but the core pin and the branch
        rec = ["--modid", "moddyarena", "--mod-dir", "arena", "--also-path", "shared", "--dep-jar",
               f"o/core@old/old.jar={GA}:1.0.9", "--dep-jar", "o/lib@t/lib.jar=org.example:lib:2", "--gatec", "launch",
               "--kit-version", "84", "--kit-sha", "e" * 64]
        got = regenerate_args(rec, f"o/core@{tag}/{asset}={GA}:1.0.10", "main")
        assert got == ["--modid", "moddyarena", "--mod-dir", "arena", "--also-path", "shared", "--dep-jar",
                       "o/lib@t/lib.jar=org.example:lib:2", "--gatec", "launch", "--kit-version", "84", "--kit-sha",
                       "e" * 64, "--dep-jar", f"o/core@{tag}/{asset}={GA}:1.0.10", "--branch", "main"], got
        assert regenerate_args(rec, "x", "neoforge-1.21.8", keep_kit=False)[-6:] == [
            "--gatec", "launch", "--dep-jar", "x", "--branch", "neoforge-1.21.8"], "no kit: port-ci.py picks the newest"
        quiet.close()
    print("core-pins: self-test passed")
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--set", nargs=2, metavar=("WORLD", "CORE_TAG"))
    g.add_argument("--regenerate", metavar="WORLD")
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    g.add_argument("--self-test", action="store_true")
    ap.add_argument("--mmvu", help="MMVU's checkout (default: $MMVU, else ../mc-mod-version-upgrade)")
    a = ap.parse_args(argv)
    if a.self_test:
        return self_test()
    if a.check:
        return run_check()
    if a.write:
        return run_write()
    if a.regenerate:
        return run_regenerate(a.regenerate, a.mmvu)
    return run_set(a.set[0], a.set[1], a.mmvu)


if __name__ == "__main__":
    sys.exit(main())
